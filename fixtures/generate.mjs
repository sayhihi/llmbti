#!/usr/bin/env node
/**
 * 테스트용 가짜 로그 생성기. 실제 로그는 포맷 참고만 했고 내용은 전부 지어낸 것이다.
 *
 *   node fixtures/generate.mjs
 *
 * 생성물 (결정적, 같은 입력이면 같은 파일):
 *   fixtures/home-j/     J형 테스터 (구체적, 건조, 계획적, 테스트 많이 돌림)      → ISTJ 근처
 *   fixtures/home-p/     P형 force-pusher (질문 많고, 감정 표현, 새벽, --force)  → ENFP 근처
 *   fixtures/home-tiny/  표본 부족 (프롬프트 5개, 셸 10개)                        → insufficient
 *
 * 기준 시각은 2026-11-01T00:00:00Z 이고, 테스트는 --now 2026-11-01T12:00:00Z --tz 540 으로 돌린다.
 */

import { mkdirSync, writeFileSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(fileURLToPath(import.meta.url));
const BASE = Date.parse("2026-11-01T00:00:00Z");
const DAY = 86_400_000;
const KST = 9 * 3_600_000;

/** 결정적 PRNG (mulberry32) */
function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** daysAgo일 전, 로컬(KST) hour시 minute분의 epoch ms */
function at(daysAgo, hour, minute = 0) {
  return BASE - daysAgo * DAY + hour * 3_600_000 + minute * 60_000 - KST;
}

const iso = (ms) => new Date(ms).toISOString();

function userLine(sessionId, text, ts, extra = {}) {
  return JSON.stringify({
    parentUuid: null,
    isSidechain: false,
    promptId: `p-${ts}`,
    type: "user",
    message: { role: "user", content: text },
    uuid: `u-${ts}`,
    timestamp: iso(ts),
    userType: "external",
    cwd: "/Users/tester/work/app",
    sessionId,
    version: "2.1.0",
    gitBranch: "main",
    ...extra,
  });
}

function assistantToolUse(sessionId, name, input, ts) {
  return JSON.stringify({
    parentUuid: "x",
    isSidechain: false,
    type: "assistant",
    uuid: `a-${ts}`,
    timestamp: iso(ts),
    message: {
      id: "msg_x",
      model: "claude-fable-5-1",
      role: "assistant",
      type: "message",
      content: [{ type: "tool_use", id: `toolu_${ts}`, name, input }],
      stop_reason: "tool_use",
    },
    sessionId,
  });
}

function toolResultLine(sessionId, ts) {
  return JSON.stringify({
    parentUuid: "x",
    isSidechain: false,
    type: "user",
    message: {
      role: "user",
      content: [{ tool_use_id: `toolu_${ts}`, type: "tool_result", content: "ok" }],
    },
    uuid: `r-${ts}`,
    timestamp: iso(ts),
    toolUseResult: { stdout: "ok", stderr: "", interrupted: false },
    sessionId,
  });
}

function assistantText(sessionId, text, ts) {
  return JSON.stringify({
    parentUuid: "x",
    isSidechain: false,
    type: "assistant",
    uuid: `t-${ts}`,
    timestamp: iso(ts),
    message: { role: "assistant", type: "message", content: [{ type: "text", text }] },
    sessionId,
  });
}

/**
 * 세션 하나를 jsonl 줄 배열로. prompts: [{text, ts, tool?: {name, input}, interrupt?: boolean}]
 */
function session(sessionId, prompts, { planMode = false, noise = true } = {}) {
  const lines = [];
  const first = prompts[0].ts;
  if (noise) {
    lines.push(JSON.stringify({ type: "mode", mode: "default", sessionId }));
    lines.push(
      JSON.stringify({
        type: "permission-mode",
        permissionMode: planMode ? "plan" : "default",
        sessionId,
      }),
    );
    lines.push(
      userLine(
        sessionId,
        "<command-name>/clear</command-name>\n<command-message>clear</command-message>",
        first - 5000,
      ),
    );
    lines.push(
      userLine(
        sessionId,
        "<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>",
        first - 4000,
        { isMeta: true },
      ),
    );
    // 서브에이전트(sidechain) 줄은 제외돼야 한다
    lines.push(
      userLine(
        sessionId,
        "서브에이전트에게 보내는 지시. 이건 프롬프트로 세면 안 된다",
        first - 3000,
        { isSidechain: true },
      ),
    );
    lines.push(
      assistantToolUse(
        sessionId,
        "Read",
        { file_path: "/Users/tester/work/app/src/a.ts" },
        first - 2500,
      ).replace('"isSidechain":false', '"isSidechain":true'),
    );
  }
  for (const p of prompts) {
    lines.push(userLine(sessionId, p.text, p.ts));
    if (p.tool) {
      lines.push(assistantToolUse(sessionId, p.tool.name, p.tool.input, p.ts + 1500));
      lines.push(toolResultLine(sessionId, p.ts + 3000));
    }
    lines.push(assistantText(sessionId, "처리했다.", p.ts + 4000));
    if (p.interrupt) {
      lines.push(
        JSON.stringify({
          parentUuid: "x",
          isSidechain: false,
          type: "user",
          message: {
            role: "user",
            content: [{ type: "text", text: "[Request interrupted by user]" }],
          },
          uuid: `i-${p.ts}`,
          timestamp: iso(p.ts + 5000),
          sessionId,
        }),
      );
    }
  }
  if (noise) {
    lines.push(JSON.stringify({ type: "last-prompt", lastPrompt: "x", leafUuid: "y", sessionId }));
    lines.push("{this line is broken json");
  }
  return lines;
}

function historyLine(text, ts, project = "/Users/tester/work/app", pasted = false) {
  const pastedContents = pasted
    ? {
        1: {
          id: 1,
          type: "text",
          content:
            "TypeError: Cannot read properties of undefined (reading 'map')\n    at render (/Users/tester/work/app/src/list.tsx:42:17)",
        },
      }
    : {};
  return JSON.stringify({ display: text, pastedContents, timestamp: ts, project });
}

function writeHome(name, { sessions, history, zsh, bash }) {
  const home = join(ROOT, name);
  rmSync(home, { recursive: true, force: true });
  const proj = join(home, ".claude", "projects", "-Users-tester-work-app");
  mkdirSync(proj, { recursive: true });
  for (const [id, lines] of Object.entries(sessions)) {
    writeFileSync(join(proj, `${id}.jsonl`), lines.join("\n") + "\n");
  }
  writeFileSync(join(home, ".claude", "history.jsonl"), history.join("\n") + "\n");
  if (zsh) writeFileSync(join(home, ".zsh_history"), zsh.join("\n") + "\n");
  if (bash) writeFileSync(join(home, ".bash_history"), bash.join("\n") + "\n");
  writeFileSync(
    join(home, "README.md"),
    `# ${name}\n\n가짜 홈 디렉터리. \`node fixtures/generate.mjs\` 로 다시 만든다. 손으로 고치지 않는다.\n`,
  );
}

